import { passwordProblem, usernameProblem } from './account';
import type { ImportRowResult, NewAccount } from './adminAccounts';

/**
 * CSV → validated account rows, for the bulk import screen.
 *
 * ⚠️ EVERY RULE HERE IS A MIRROR, NOT A SOURCE. `CreateAccountSchema` on the
 * server is authoritative and re-validates all of it; this exists so an admin
 * pasting fifty rows sees every problem at once, before anything is written,
 * instead of discovering row 34 after 33 accounts already exist.
 *
 * No CSV dependency. The format we accept is a header row plus comma-separated
 * values with optional double-quoting — enough for a spreadsheet export, and a
 * parser small enough to read in one sitting is worth more here than RFC 4180
 * completeness for a file an administrator typed.
 */

/**
 * ⚠️ THE TEMPLATE HAS NO `username` AND NO `password` COLUMN, DELIBERATELY.
 *
 * Both are generated by the server and handed back in the credentials file at the
 * end of the import, so asking the admin to supply them is asking for work whose
 * output is thrown away — and inventing fifty usernames by hand is exactly the
 * failure `suggestUsername()` exists to remove. What is left is only what the
 * school actually knows about a person: who they are, what they are, and how to
 * reach them.
 *
 * ⚠️ THE PARSER STILL ACCEPTS BOTH IF PRESENT — see `parseAccountsCsv()`. That is
 * not a leftover: a file made from the older template must keep working, and an
 * educator occasionally warrants a chosen username (`a.santos`). Not offering
 * them and refusing them are different things.
 */
export const CSV_COLUMNS = ['role', 'first_name', 'last_name', 'grade_level', 'email'] as const;

/** Only these three must be present. `grade_level` is required by VALUE for a
 * student (see `validate()`), but a file of educators legitimately has no such
 * column at all. */
export const REQUIRED_COLUMNS = ['role', 'first_name', 'last_name'] as const;

/** Accepted when supplied, absent from the template, never required. */
export const OPTIONAL_COLUMNS = ['username', 'password'] as const;

export const CSV_TEMPLATE = `role,first_name,last_name,grade_level,email
student,Juan,Dela Cruz,9,
student,Maria,Reyes,7,maria.reyes@example.com
educator,Ana,Santos,,ana.santos@pca.edu.ph`;

/**
 * A shape check, not an email validator — the server's `.email()` is the real
 * rule and a browser-side regex that disagrees with it is worse than none.
 *
 * Exported so `ImportAccountsModal` filters the precheck payload by exactly this
 * test: `ImportPrecheckSchema` rejects the whole array if one entry is malformed,
 * and a row with a bad address already carries its own error from `validate()`.
 */
export const EMAIL_SHAPE = /^[^@\s]+@[^@\s]+\.[^@\s]+$/;

export interface ParsedRow {
  /**
   * 1-based line number **in the file, header included** — the number the admin's
   * spreadsheet shows in its row gutter. The header is line 1, so the first
   * account is line 2.
   *
   * ⚠️ THIS USED TO BE THE LOOP INDEX OVER DATA ROWS, AND EVERY NUMBER AN ADMIN
   * SAW WAS ONE TOO LOW. Reported from a real 31-student import: a genuine
   * duplicate on spreadsheet row 30 was labelled row 29 and cross-referenced to
   * "row 16" when the clashing address was on row 17 — so following the message
   * landed on an unrelated student and the importer read as broken. Blank lines
   * are also skipped, so this is carried through the filter rather than
   * recomputed from the surviving rows' positions.
   */
  line: number;
  account: NewAccount;
  /** Empty when the row is usable. */
  errors: string[];
}

export interface ParseResult {
  rows: ParsedRow[];
  /** A problem with the file as a whole — a bad header, or nothing to import. */
  fatal: string | null;
}

/**
 * Split one CSV line, honouring double-quoted fields containing commas.
 * `""` inside a quoted field is a literal quote, per the usual convention.
 */
function splitLine(line: string): string[] {
  const out: string[] = [];
  let field = '';
  let inQuotes = false;

  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (inQuotes) {
      if (ch === '"') {
        if (line[i + 1] === '"') {
          field += '"';
          i++;
        } else {
          inQuotes = false;
        }
      } else {
        field += ch;
      }
    } else if (ch === '"') {
      inQuotes = true;
    } else if (ch === ',') {
      out.push(field);
      field = '';
    } else {
      field += ch;
    }
  }
  out.push(field);
  return out.map((f) => f.trim());
}

function validate(account: NewAccount, raw: Record<string, string>): string[] {
  const errors: string[] = [];

  if (account.role !== 'student' && account.role !== 'educator') {
    // Deliberately names the two: `admin` is not assignable here, and someone
    // will try it before reading the docs.
    errors.push(`Role must be "student" or "educator" (got "${raw.role || 'blank'}")`);
  }
  if (!account.first_name) errors.push('First name is required');
  if (!account.last_name) errors.push('Last name is required');

  /*
   * A BLANK USERNAME IS VALID — the server generates one from the name. Fifty
   * students should not need fifty hand-written usernames. Only a username that
   * was actually supplied is checked against the format rules.
   */
  if (account.username) {
    const usernameError = usernameProblem(account.username);
    if (usernameError) errors.push(usernameError);
  }

  /*
   * ⚠️ A STUDENT WITHOUT A GRADE IS REJECTED, NEVER DEFAULTED.
   * `handle_new_user()` silently assigns Grade 7 to a student created without
   * one, and that default decides which year's materials the account can open
   * for the rest of its life. It must be a deliberate choice in the file.
   */
  if (account.role === 'student') {
    if (raw.grade_level === '') {
      errors.push('A student needs a grade level (7–10)');
    } else if (
      account.grade_level === undefined ||
      account.grade_level === null ||
      Number.isNaN(account.grade_level)
    ) {
      errors.push(`Grade level must be a number 7–10 (got "${raw.grade_level}")`);
    } else if (account.grade_level < 7 || account.grade_level > 10) {
      errors.push(`Grade level must be 7–10 (got ${account.grade_level})`);
    }
  } else if (account.role === 'educator' && raw.grade_level !== '') {
    errors.push('An educator has no grade level — leave it blank');
  }

  if (raw.email && !EMAIL_SHAPE.test(raw.email)) {
    errors.push(`"${raw.email}" is not a valid email address`);
  }
  /*
   * Only a SUPPLIED password is checked. Blank means "generate one", and the
   * generated form (`brave-otter-93`) satisfies the same rule via its hyphens.
   */
  if (raw.password) {
    const problem = passwordProblem(raw.password);
    if (problem) errors.push(`${problem} Or leave the column blank to generate one.`);
  }

  return errors;
}

// ── writing: the credentials handed out after an import ─────────────────────

/**
 * ⚠️ THE NAME COLUMNS ARE THE POINT OF THIS FILE, NOT AN EXTRA.
 *
 * The admin distributes these credentials to up to fifty children. A list of
 * usernames and passwords alone cannot be handed out — nothing on it says whose
 * line is whose, and the generated usernames (`juan.delacruz`) only *look*
 * self-explanatory until two students share a name and become `maria.santos` and
 * `maria.santos2`.
 *
 * Ordered first/last to match the import template's own column names, so a file
 * that comes out can be sorted, mail-merged, or pasted back beside the one that
 * went in.
 */
export const CREDENTIAL_HEADER = ['first_name', 'last_name', 'username', 'password'] as const;

/**
 * ⚠️ SUCCESSFUL ROWS ONLY. A failed row carries no password, and a blank cell in
 * a credentials file reads as an account whose password is empty rather than one
 * that was never created.
 *
 * Names come from the server's result rows. Never re-derive them by matching
 * index against the rows that were sent: a row can drop out of the results (a
 * name yielding no username is reported and skipped), which would shift every
 * subsequent name by one and hand children each other's passwords.
 */
export function credentialRows(results: ImportRowResult[]): string[][] {
  return results
    .filter((r) => r.ok)
    .map((r) => [r.first_name, r.last_name, r.username, r.password ?? '']);
}

/**
 * One CSV cell, quoted only when it has to be — the writing counterpart of
 * `splitLine()` above, and it must stay its exact inverse.
 *
 * ⚠️ NOT OPTIONAL NOW THAT NAMES ARE IN THE FILE. A surname entered as
 * `Dela Cruz, Juan` would otherwise split into two columns and push the password
 * one cell across, handing a child someone else's credentials. A password typed
 * into the import file can contain a comma for the same reason — the rule on it
 * is only "eight characters, one of them not a letter or digit".
 */
export function csvCell(value: string): string {
  return /[",\r\n]/.test(value) ? `"${value.replace(/"/g, '""')}"` : value;
}

/** Header + rows as a CSV file, trailing newline included. */
export function toCsv(header: readonly string[], rows: string[][]): string {
  return [header.map(csvCell).join(','), ...rows.map((r) => r.map(csvCell).join(','))].join('\n') + '\n';
}

/**
 * Hand a CSV string to the browser as a file — blob → object URL → click →
 * revoke.
 *
 * Lives beside `toCsv()` because it is the other half of the same job and had
 * been written out by hand at every call site. Note this works only on a page the
 * user is on: a published Artifact's sandbox blocks script-driven downloads.
 */
export function downloadCsvFile(content: string, filename: string): void {
  const blob = new Blob([content], { type: 'text/csv' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

/**
 * Header + rows tab-separated, for the clipboard. That is what a spreadsheet
 * expects on paste, and it sidesteps quoting entirely — no cell here can contain
 * a tab, since names come from a CSV that was itself split on commas.
 */
export function toTsv(header: readonly string[], rows: string[][]): string {
  return [header.join('\t'), ...rows.map((r) => r.join('\t'))].join('\n');
}

/**
 * Where an earlier row claimed a username or an address.
 *
 * The name rides along because a bare "already used on row 17" is not
 * self-checking: an admin has to go and look, and if the number is wrong (as it
 * was — see `ParsedRow.line`) they find an unrelated student and conclude the
 * importer is broken. With the name in the message, a wrong number is visible
 * in the message itself.
 */
interface Claim {
  line: number;
  name: string;
}

/** "James Abdiel B. Toledo", or "" when the row has no name — which is already
 * its own error, so there is nothing useful to add in that case. */
function claimantName(raw: Record<string, string>): string {
  return [raw.first_name, raw.last_name].map((p) => (p ?? '').trim()).filter(Boolean).join(' ');
}

function claimRef(claim: Claim): string {
  return claim.name ? `row ${claim.line} (${claim.name})` : `row ${claim.line}`;
}

export function parseAccountsCsv(text: string): ParseResult {
  /*
   * ⚠️ THE ORIGINAL LINE NUMBER IS CARRIED THROUGH THE BLANK-LINE FILTER, NOT
   * RECOVERED FROM A POSITION AFTERWARDS. Blank rows are routine in a
   * spreadsheet export, and every one of them would otherwise shift every
   * number below it — the admin's whole reason for trusting these numbers is
   * that they match the row gutter in Excel.
   *
   * Still line-oriented: a newline INSIDE a quoted field splits the record in
   * two, because `splitLine()` takes one line at a time. That has always been
   * true of this parser and is not something the numbering introduced.
   */
  const lines = text
    .split(/\r?\n/)
    .map((text, i) => ({ n: i + 1, text: text.trim() }))
    .filter((l) => l.text.length > 0);

  if (lines.length === 0) return { rows: [], fatal: 'The file is empty.' };

  const header = splitLine(lines[0].text).map((h) => h.toLowerCase().replace(/\s+/g, '_'));

  /*
   * `username` is NOT required here any more — it left the template, because the
   * server generates one. A file that still carries the column is parsed exactly
   * as before; see `CSV_COLUMNS` for why both spellings must keep working.
   */
  const missing = REQUIRED_COLUMNS.filter((c) => !header.includes(c));
  if (missing.length > 0) {
    return {
      rows: [],
      fatal: `The header row is missing: ${missing.join(', ')}. Expected: ${CSV_COLUMNS.join(', ')}`,
    };
  }

  if (lines.length === 1) {
    return { rows: [], fatal: 'The file has a header row but no accounts.' };
  }

  const rows: ParsedRow[] = [];
  /* Case-insensitive, matching `ux_profiles_username_lower`. Catching duplicates
   * here is what keeps a within-file collision from becoming a mid-import failure
   * with some accounts already created. */
  const seen = new Map<string, Claim>();
  /*
   * The same rule for addresses, and it is NOT optional politeness: Supabase
   * enforces a unique index on `auth.users.email` (`users_email_partial_key`), so
   * two accounts can never share one. Siblings given the same parent's Gmail is
   * the realistic way a class file hits this, and without the check the second of
   * them fails partway through the import with the first already created.
   */
  const seenEmails = new Map<string, Claim>();

  for (let i = 1; i < lines.length; i++) {
    // The file line, never the loop index — see `ParsedRow.line`. Everything the
    // admin is shown about this row, here and on the results screen, uses it.
    const line = lines[i].n;
    const cells = splitLine(lines[i].text);
    const raw: Record<string, string> = {};
    header.forEach((col, idx) => {
      raw[col] = cells[idx] ?? '';
    });

    const role = raw.role.toLowerCase() as NewAccount['role'];
    const username = (raw.username ?? '').toLowerCase();
    const gradeText = raw.grade_level ?? '';

    const account: NewAccount = {
      role,
      first_name: raw.first_name,
      last_name: raw.last_name,
      /*
       * OMITTED ENTIRELY when blank, never sent as `''`. The server's
       * `UsernameField.optional()` accepts an absent key and rejects an empty
       * string, so a blank column must not become one — that would turn "generate
       * this for me" into a validation error.
       */
      ...(username ? { username } : {}),
      ...(role === 'student' && gradeText !== ''
        ? { grade_level: Number(gradeText) }
        : {}),
      ...(raw.email ? { email: raw.email.toLowerCase() } : {}),
      ...(raw.password ? { password: raw.password } : {}),
    };

    const errors = validate(account, { ...raw, grade_level: gradeText });
    const claim: Claim = { line, name: claimantName(raw) };

    const previous = seen.get(username);
    if (username && previous !== undefined) {
      errors.push(`Duplicate username — already used on ${claimRef(previous)}`);
    } else if (username) {
      seen.set(username, claim);
    }

    // A blank email column is fine and common — only a supplied one can clash.
    const email = (raw.email ?? '').trim().toLowerCase();
    const previousEmail = seenEmails.get(email);
    if (email && previousEmail !== undefined) {
      errors.push(`Duplicate email — already used on ${claimRef(previousEmail)}`);
    } else if (email) {
      seenEmails.set(email, claim);
    }

    rows.push({ line, account, errors });
  }

  return { rows, fatal: null };
}
